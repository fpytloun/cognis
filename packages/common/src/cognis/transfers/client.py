async def file_io[T](function: Callable[..., T], *args: Any) -> T:
    """Keep cancellation from closing a file while its worker is using it."""
    task = asyncio.create_task(asyncio.to_thread(function, *args))
    try:
        return await asyncio.shield(task)
    except asyncio.CancelledError:
        with contextlib.suppress(Exception):
            await task
        raise


@asynccontextmanager
async def opened_file(path: Path) -> AsyncIterator[BinaryIO]:
    """Open/read/close off the event loop, including cancellation during open."""
    source: BinaryIO | None = None

    def open_source() -> None:
        nonlocal source
        source = path.open("rb")

    try:
        await file_io(open_source)
        assert source is not None
        yield source
    finally:
        if source is not None:
            await file_io(source.close)


async def _read_ahead(read: Callable[[], bytes]) -> AsyncGenerator[bytes]:
    """Overlap one sequential file/hash worker with HTTP, with two queued chunks."""
    queue: asyncio.Queue[bytes | Exception | None] = asyncio.Queue(maxsize=2)

    async def produce() -> None:
        try:
            while chunk := await file_io(read):
                await queue.put(chunk)
            await queue.put(None)
        except asyncio.CancelledError:
            raise
        except Exception as exc:
            await queue.put(exc)

    producer = asyncio.create_task(produce(), name="binary-file-read-ahead")
    try:
        while True:
            item = await queue.get()
            if item is None:
                return
            if isinstance(item, Exception):
                raise item
            yield item
    finally:
        producer.cancel()
        with contextlib.suppress(asyncio.CancelledError):
            await producer


class BinaryTransferClient:
    """Move files as raw HTTP streams; return only small, verified receipts."""

    def __init__(
        self,
        grant: TransferGrant | None = None,
        *,
        transport: httpx.AsyncBaseTransport | None = None,
    ) -> None:
        self.grant = grant
        self.transport = transport
        self._next_slot = 0

    def _http(self) -> httpx.AsyncClient:
        return httpx.AsyncClient(
            transport=self.transport,
            timeout=httpx.Timeout(60, connect=15, pool=15),
            follow_redirects=False,
        )

    def attachment_content(self, content: bytes) -> dict[str, Any]:
        """Keep generated bytes native; retain the older controller's deployed format."""
        if self.grant is not None:
            return {"content_bytes": content}
        return {"content_b64": base64.b64encode(content).decode("ascii")}

    async def prepare_attachments(self, attachments: list[Any] | None) -> list[Any] | None:
        """Move generated/MCP binary bodies off RPC without changing their metadata."""
        if self.grant is None or not attachments:
            return attachments
        prepared = []
        for attachment in attachments:
            if not isinstance(attachment, dict):
                prepared.append(attachment)
                continue
            encoded = attachment.get("content_b64")
            content = attachment.get("content_bytes")
            if not isinstance(encoded, str) and not isinstance(content, bytes):
                prepared.append(attachment)
                continue
            staging: Path | None = None
            target: BinaryIO | None = None

            def open_target() -> None:
                nonlocal staging, target
                descriptor, name = tempfile.mkstemp()
                staging = Path(name)
                target = os.fdopen(descriptor, "w+b")

            try:
                await file_io(open_target)
                assert target is not None and staging is not None
                if isinstance(content, bytes):
                    for offset in range(0, len(content), TRANSFER_CHUNK_BYTES):
                        await file_io(target.write, content[offset : offset + TRANSFER_CHUNK_BYTES])
                else:
                    assert isinstance(encoded, str)
                    for offset in range(0, len(encoded), TRANSFER_CHUNK_BYTES):
                        chunk = base64.b64decode(encoded[offset : offset + TRANSFER_CHUNK_BYTES])
                        await file_io(target.write, chunk)
                await file_io(target.close)
                receipt = await self.upload_file(
                    staging,
                    filename=str(attachment.get("filename") or "attachment"),
                    mime_type=str(attachment.get("mime_type") or "application/octet-stream"),
                )
                prepared.append(
                    {
                        **{
                            key: value
                            for key, value in attachment.items()
                            if key not in {"content_b64", "content_bytes"}
                        },
                        "transfer_receipt": receipt.model_dump(),
                    }
                )
            finally:
                if target is not None:
                    await file_io(target.close)
                if staging is not None:
                    await file_io(staging.unlink, True)
        return prepared

    async def upload_file(
        self,
        path: Path,
        *,
        filename: str | None = None,
        mime_type: str = "application/octet-stream",
    ) -> TransferReceipt:
        """Stream an opened, stable source; reconcile uncertain HTTP completion."""
        if self.grant is None:
            raise ValueError("Native binary upload was not authorized for this call")
        slot = self._next_slot
        self._next_slot += 1
        headers = {"Authorization": f"Bearer {self.grant.token}"}
        async with opened_file(path) as source, self._http() as http:
            before = await file_io(os.fstat, source.fileno())
            request = UploadRequest(
                slot=slot,
                filename=filename or path.name,
                mime_type=mime_type,
                size_bytes=before.st_size,
            )
            response = await http.post(self.grant.url, headers=headers, json=request.model_dump())
            response.raise_for_status()
            descriptor = UploadDescriptor.model_validate(response.json())
            digest = hashlib.sha256()
            count = 0

            def read_hashed() -> bytes:
                chunk = source.read(TRANSFER_CHUNK_BYTES)
                digest.update(chunk)
                return chunk

            async def content() -> AsyncGenerator[bytes]:
                nonlocal count
                reader = _read_ahead(read_hashed)
                try:
                    async for chunk in reader:
                        count += len(chunk)
                        yield chunk
                finally:
                    await reader.aclose()
                after = await file_io(os.fstat, source.fileno())
                if (after.st_size, after.st_mtime_ns) != (before.st_size, before.st_mtime_ns):
                    raise ValueError("Transfer source changed while being read")

            try:
                stream = content()
                try:
                    response = await http.put(
                        descriptor.url,
                        headers={**headers, "Content-Length": str(before.st_size)},
                        content=stream,
                    )
                finally:
                    await stream.aclose()
                response.raise_for_status()
                receipt = TransferReceipt.model_validate(response.json())
            except httpx.TransportError:
                # A lost response is not permission to repeat the upload.
                status = await http.get(
                    f"{self.grant.url}/{descriptor.transfer_id}", headers=headers
                )
                status.raise_for_status()
                reconciled = UploadDescriptor.model_validate(status.json())
                if reconciled.receipt is None:
                    raise
                receipt = reconciled.receipt
            if count != receipt.size_bytes or digest.hexdigest() != receipt.sha256:
                raise ValueError("Binary transfer integrity verification failed")
            return receipt

    async def download_file(
        self,
        descriptor: DownloadDescriptor,
        destination: Path,
        *,
        before_replace: Callable[[], Awaitable[None]] | None = None,
    ) -> int:
        """Verify bytes before atomically exposing a downloaded file."""
        target: BinaryIO | None = None
        staging: Path | None = None

        def open_target() -> None:
            nonlocal target, staging
            destination.parent.mkdir(parents=True, exist_ok=True)
            descriptor, name = tempfile.mkstemp(dir=destination.parent)
            staging = Path(name)
            target = os.fdopen(descriptor, "w+b")

        try:
            await file_io(open_target)
            assert target is not None and staging is not None
            digest = hashlib.sha256()
            total = 0
            async with self._http() as http, http.stream("GET", descriptor.url) as response:
                response.raise_for_status()
                async for chunk in response.aiter_bytes(TRANSFER_CHUNK_BYTES):
                    total += len(chunk)
                    if total > descriptor.size_bytes:
                        raise ValueError("Download exceeds its declared length")
                    digest.update(chunk)
                    await file_io(target.write, chunk)
            if total != descriptor.size_bytes:
                raise ValueError("Download is truncated")
            if descriptor.sha256 is not None and digest.hexdigest() != descriptor.sha256:
                raise ValueError("Download integrity verification failed")
            if before_replace is not None:
                await before_replace()
            await file_io(target.flush)
            await file_io(os.fsync, target.fileno())
            await file_io(target.close)
            await file_io(os.replace, staging, destination)
            return total
        finally:
            if target is not None:
                await file_io(target.close)
            if staging is not None:
                await file_io(staging.unlink, True)
